CREATE TABLE benutzer (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          e_mail VARCHAR(254) NOT NULL UNIQUE,
                          passwort_hash VARCHAR(255) NOT NULL,
                          anzeigename VARCHAR(50) NOT NULL,
                          erstellt_am TIMESTAMP NOT NULL,
                          aktualisiert_am TIMESTAMP NOT NULL,

                          CONSTRAINT chk_benutzer_anzeigename
                              CHECK (char_length(anzeigename) BETWEEN 3 AND 50)
);


CREATE TABLE profile (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         benutzer_id BIGINT NOT NULL UNIQUE,
                         ueber_mich TEXT,
                         standort VARCHAR(120),
                         arbeitsweise VARCHAR(20),
                         github_link VARCHAR(500),
                         linkedin_link VARCHAR(500),
                         erstellt_am TIMESTAMP NOT NULL,
                         aktualisiert_am TIMESTAMP NOT NULL,

                         CONSTRAINT fk_profile_benutzer
                             FOREIGN KEY (benutzer_id)
                                 REFERENCES benutzer(id),

                         CONSTRAINT chk_profile_arbeitsweise
                             CHECK (
                                 arbeitsweise IS NULL
                                     OR arbeitsweise IN ('REMOTE', 'VOR_ORT', 'HYBRID')
                                 ),

                         CONSTRAINT chk_profile_ueber_mich
                             CHECK (
                                 ueber_mich IS NULL
                                     OR char_length(ueber_mich) <= 1000
                                 )
);


CREATE TABLE kategorien (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR NOT NULL UNIQUE
);


CREATE TABLE technologien (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              name VARCHAR NOT NULL UNIQUE
);


CREATE TABLE anzeigen (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          eigentuemer_id BIGINT NOT NULL,
                          kategorie_id BIGINT NOT NULL,

                          titel VARCHAR(120) NOT NULL,
                          beschreibung TEXT NOT NULL,

                          anzeigentyp VARCHAR(40) NOT NULL,
                          projektstand VARCHAR(40),
                          arbeitsweise VARCHAR(20) NOT NULL,

                          standort VARCHAR(120),
                          projektlink VARCHAR(500),

                          status VARCHAR(20) NOT NULL,

                          erstellt_am TIMESTAMP NOT NULL,
                          aktualisiert_am TIMESTAMP NOT NULL,
                          geschlossen_am TIMESTAMP,
                          geloescht_am TIMESTAMP,

                          CONSTRAINT fk_anzeigen_eigentuemer
                              FOREIGN KEY (eigentuemer_id)
                                  REFERENCES benutzer(id),

                          CONSTRAINT fk_anzeigen_kategorie
                              FOREIGN KEY (kategorie_id)
                                  REFERENCES kategorien(id),

                          CONSTRAINT chk_anzeigen_titel
                              CHECK (char_length(titel) BETWEEN 5 AND 120),

                          CONSTRAINT chk_anzeigen_beschreibung
                              CHECK (char_length(beschreibung) BETWEEN 20 AND 5000),

                          CONSTRAINT chk_anzeigen_anzeigentyp
                              CHECK (
                                  anzeigentyp IN (
                                                  'UNTERSTUETZUNG_GESUCHT',
                                                  'PROJEKT_GESUCHT'
                                      )
                                  ),

                          CONSTRAINT chk_anzeigen_projektstand
                              CHECK (
                                  projektstand IS NULL
                                      OR projektstand IN (
                                                          'IDEE_PLANUNG',
                                                          'IN_ENTWICKLUNG',
                                                          'PROTOTYP_VORHANDEN'
                                      )
                                  ),

                          CONSTRAINT chk_anzeigen_arbeitsweise
                              CHECK (
                                  arbeitsweise IN (
                                                   'REMOTE',
                                                   'VOR_ORT',
                                                   'HYBRID'
                                      )
                                  ),

                          CONSTRAINT chk_anzeigen_status
                              CHECK (
                                  status IN (
                                             'ACTIVE',
                                             'CLOSED'
                                      )
                                  )
);


CREATE TABLE anzeige_technologien (
                                      anzeige_id BIGINT NOT NULL,
                                      technologie_id BIGINT NOT NULL,

                                      PRIMARY KEY (anzeige_id, technologie_id),

                                      CONSTRAINT fk_anzeige_technologien_anzeige
                                          FOREIGN KEY (anzeige_id)
                                              REFERENCES anzeigen(id),

                                      CONSTRAINT fk_anzeige_technologien_technologie
                                          FOREIGN KEY (technologie_id)
                                              REFERENCES technologien(id)
);


CREATE TABLE profil_technologien (
                                     profil_id BIGINT NOT NULL,
                                     technologie_id BIGINT NOT NULL,

                                     PRIMARY KEY (profil_id, technologie_id),

                                     CONSTRAINT fk_profil_technologien_profil
                                         FOREIGN KEY (profil_id)
                                             REFERENCES profile(id),

                                     CONSTRAINT fk_profil_technologien_technologie
                                         FOREIGN KEY (technologie_id)
                                             REFERENCES technologien(id)
);


CREATE TABLE unterhaltungen (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                anzeige_id BIGINT NOT NULL,
                                eigentuemer_id BIGINT NOT NULL,
                                interessent_id BIGINT NOT NULL,
                                erstellt_am TIMESTAMP NOT NULL,
                                aktualisiert_am TIMESTAMP NOT NULL,

                                CONSTRAINT fk_unterhaltungen_anzeige
                                    FOREIGN KEY (anzeige_id)
                                        REFERENCES anzeigen(id),

                                CONSTRAINT fk_unterhaltungen_eigentuemer
                                    FOREIGN KEY (eigentuemer_id)
                                        REFERENCES benutzer(id),

                                CONSTRAINT fk_unterhaltungen_interessent
                                    FOREIGN KEY (interessent_id)
                                        REFERENCES benutzer(id),

                                CONSTRAINT uq_unterhaltungen_anzeige_interessent
                                    UNIQUE (anzeige_id, interessent_id),

                                CONSTRAINT chk_unterhaltungen_teilnehmer
                                    CHECK (eigentuemer_id <> interessent_id)
);


CREATE TABLE nachrichten (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             unterhaltung_id BIGINT NOT NULL,
                             absender_id BIGINT NOT NULL,
                             inhalt TEXT NOT NULL,
                             gesendet_am TIMESTAMP NOT NULL,
                             gelesen BOOLEAN NOT NULL DEFAULT FALSE,

                             CONSTRAINT fk_nachrichten_unterhaltung
                                 FOREIGN KEY (unterhaltung_id)
                                     REFERENCES unterhaltungen(id),

                             CONSTRAINT fk_nachrichten_absender
                                 FOREIGN KEY (absender_id)
                                     REFERENCES benutzer(id),

                             CONSTRAINT chk_nachrichten_inhalt
                                 CHECK (char_length(inhalt) BETWEEN 1 AND 2000)
);